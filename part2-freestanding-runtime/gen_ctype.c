/* gen_ctype.c - build-time helper. Dumps glibc's real ctype tables (indices
 * -128..255) as C arrays into ctype_table.h, so the freestanding __ctype_*_loc
 * match the exact bit layout Lua's lstrlib expects. Run once during the build. */
#include <ctype.h>
#include <stdio.h>
int main(void){
  const unsigned short *b = *__ctype_b_loc();
  const int *lo = *__ctype_tolower_loc();
  const int *up = *__ctype_toupper_loc();
  printf("/* generated by gen_ctype.c */\n");
  printf("static const unsigned short CB[384]={");
  for(int i=-128;i<256;i++){ printf("%u,", b[i]); } printf("};\n");
  printf("static const int CL[384]={"); for(int i=-128;i<256;i++) printf("%d,", lo[i]); printf("};\n");
  printf("static const int CU[384]={"); for(int i=-128;i<256;i++) printf("%d,", up[i]); printf("};\n");
  return 0;
}
