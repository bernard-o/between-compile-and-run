-- Generate render_bc.h from a Lua source file (stripped bytecode embedded as a
-- C array). Usage: lua gen_bytecode.lua render.lua render_bc.h
local src, out = arg[1], arg[2]
local f = assert(loadfile(src))
local bc = string.dump(f, true)          -- true = strip debug info
local o = assert(io.open(out, "w"))
o:write("/* generated by gen_bytecode.lua from ", src, " - do not edit */\n")
o:write("static const unsigned char RENDER_BC[] = {\n")
for i = 1, #bc do
  o:write(string.format("0x%02x,", bc:byte(i)))
  if i % 16 == 0 then o:write("\n") end
end
o:write("\n};\nstatic const unsigned int RENDER_BC_LEN = ", #bc, ";\n")
o:close()
io.write(("render_bc.h: %d bytes of bytecode\n"):format(#bc))
